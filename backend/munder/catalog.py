import difflib

# Lookups derived from the catalog (data above is the single source of truth).
CATALOG_PRICE = {item["item_name"]: item["unit_price"] for item in paper_supplies}
_CATALOG_LOWER = {name.lower(): name for name in CATALOG_PRICE}


def canonical_item_name(name: str) -> str:
    """Map a free-text item name to the exact catalog name: exact match, then
    case-insensitive, then closest fuzzy match. Falls back to the input if nothing
    reasonable matches. Keeps agent-supplied names aligned with real inventory."""
    if name in CATALOG_PRICE:
        return name
    low = name.lower().strip()
    if low in _CATALOG_LOWER:
        return _CATALOG_LOWER[low]
    match = difflib.get_close_matches(low, list(_CATALOG_LOWER.keys()), n=1, cutoff=0.6)
    return _CATALOG_LOWER[match[0]] if match else name
